// ───────────── The page ─────────────
class RequestPage extends StatefulWidget {
  final Ctl c;
  const RequestPage({super.key, required this.c});
  @override
  State<RequestPage> createState() => _RequestPageState();
}

class _RequestPageState extends State<RequestPage> {
  // STATE: the key that identifies the Form and gives access to validate / save / reset.
  final GlobalKey<FormState> _formKey = GlobalKey<FormState>();
  // Lets us re-validate only the phone field when the contact method changes.
  final GlobalKey<FormFieldState<String>> _phoneKey = GlobalKey<FormFieldState<String>>();

  // Text controllers (disposed in dispose()).
  final TextEditingController _nameCtl = TextEditingController();
  final TextEditingController _idCtl = TextEditingController();
  final TextEditingController _emailCtl = TextEditingController();
  final TextEditingController _phoneCtl = TextEditingController();
  final TextEditingController _extraCtl = TextEditingController();
  final TextEditingController _subjectCtl = TextEditingController();
  final TextEditingController _descCtl = TextEditingController();
  final TextEditingController _lookupCtl = TextEditingController(); // "look up by reference" (outside the Form)

  // STATE: values that live outside the text controllers. Reset must clear these too.
  String? _category, _urgency, _contact, _attachment;
  DateTime? _date;
  bool _agree = false;

  final RequestDraft _draft = RequestDraft();

  // FIREBASE STATE
  bool _isSubmitting = false; // a write is in flight (blocks repeated taps)
  bool _pendingSync = false; // the write has not been acknowledged yet (probably offline)
  String? _lastRequestId; // set ONLY after the server acknowledged the write
  String? _submitError; // readable message of the last failed attempt
  Timer? _pendingTimer;
  // Kept while the outcome of a write is uncertain, so a retry never creates a second ID.
  DocumentReference<Map<String, dynamic>>? _retainedRef;

  // "My requests" list loaded from Firestore
  List<StoredRequest> _mine = [];
  bool _mineLoading = false;
  String? _mineError;
  String? _lookupError;

  late final List<TextEditingController> _all = [_nameCtl, _idCtl, _emailCtl, _phoneCtl, _extraCtl, _subjectCtl, _descCtl];

  @override
  void initState() {
    super.initState();
    // Rebuild whenever any text changes so the progress bar stays live.
    for (final t in _all) {
      t.addListener(_refresh);
    }
    // Returning student (already signed in): show their saved requests straight away.
    if (FirebaseAuth.instance.currentUser != null) {
      WidgetsBinding.instance.addPostFrameCallback((_) => _loadMine());
    }
  }

  @override
  void dispose() {
    // Dispose every controller to avoid memory leaks.
    _pendingTimer?.cancel();
    for (final t in _all) {
      t.removeListener(_refresh);
      t.dispose();
    }
    _lookupCtl.dispose();
    super.dispose();
  }

  void _refresh() {
    if (mounted) setState(() {});
  }

  ServiceCat? get _cat {
    for (final s in serviceCats) {
      if (s.name == _category) return s;
    }
    return null;
  }

  bool get _hasExtra => _cat != null && _cat!.extraLabel.isNotEmpty;

  String? _vExtra(String? v) {
    if ((v ?? '').trim().length < 3) return 'Please add the ${_cat?.extraLabel.toLowerCase() ?? 'detail'} (at least 3 characters).';
    return null;
  }

  // Phone is optional, EXCEPT when the student wants to be reached by phone.
  String? _vPhoneField(String? v) {
    if (_contact == 'Phone' && (v ?? '').trim().isEmpty) return 'Enter a phone number, because you chose a phone call.';
    return vPhone(v);
  }

  // PROGRESS: counts how many required items currently pass their validator.
  List<bool> _checks() => [
    vName(_nameCtl.text) == null,
    vStudentId(_idCtl.text) == null,
    vEmail(_emailCtl.text) == null,
    if (_contact == 'Phone') _vPhoneField(_phoneCtl.text) == null,
    _category != null,
    if (_hasExtra) _vExtra(_extraCtl.text) == null,
    vSubject(_subjectCtl.text) == null,
    vDescription(_descCtl.text) == null,
    _urgency != null,
    _contact != null,
    vDate(_date) == null,
    _agree,
  ];

  // Fills the student details from the profile (sample data) to save typing.
  void _useProfile() {
    setState(() {
      _nameCtl.text = kName;
      _idCtl.text = kId;
      _emailCtl.text = kEmail;
    });
    widget.c.snack('Student details filled from your profile');
  }

  // Builds the Firestore document. Field names and types match firestore.rules exactly.
  Map<String, dynamic> _buildPayload(String uid) {
    final d = _draft;
    final date = d.date!;
    return {
      'ownerUid': uid,
      'studentName': d.name.trim(),
      'studentId': d.studentId.trim(),
      'email': d.email.trim(),
      'phone': d.phone.trim(), // empty string when omitted
      'serviceCategory': d.category,
      'subject': d.subject.trim(),
      'description': d.description.trim(),
      'urgency': d.urgency, // Low | Normal | High
      'preferredContact': d.contact, // Email | Phone
      // A calendar date (campus time zone): stored as local midnight of the chosen day.
      'preferredDate': Timestamp.fromDate(DateTime(date.year, date.month, date.day)),
      'declaration': _agree,
      'status': 'submitted',
      'createdAt': FieldValue.serverTimestamp(), // filled in by the server
      // Optional extras of this app (also allowed by firestore.rules):
      'extraDetail': d.extra.trim(),
      'attachmentName': d.attachment ?? '',
    };
  }

  // SUBMIT: validate first, save only if everything passes, WRITE to Firestore,
  // and show success only after the server acknowledged the write.
  Future<void> _submit() async {
    if (_isSubmitting || _lastRequestId != null) return; // repeated-tap guard: one pending operation only
    final form = _formKey.currentState;
    if (form == null) return;
    FocusScope.of(context).unfocus();

    if (!form.validate()) {
      // Failed validation: stay on the form, keep every valid value, show errors beside fields.
      // Nothing is sent to Firestore.
      widget.c.snack('Please fix the highlighted fields before submitting.');
      return;
    }
    _draft.extra = ''; // cleared first, so a field that is no longer shown cannot leak an old value
    _draft.attachment = _attachment; // the attachment is not a FormField, so copy it here
    form.save(); // runs every onSaved callback and fills _draft

    setState(() {
      _isSubmitting = true;
      _pendingSync = false;
      _submitError = null;
    });
    // If the write is not acknowledged within 6 seconds we show "Pending sync".
    // The write itself is NOT cancelled and NO new ID is created.
    _pendingTimer?.cancel();
    _pendingTimer = Timer(const Duration(seconds: 6), () {
      if (mounted && _isSubmitting) setState(() => _pendingSync = true);
    });

    try {
      final user = await CampusBackend.ensureUser();
      final isRetry = _retainedRef != null;
      final ref = _retainedRef ?? CampusBackend.newRef(); // reuse the same ID on a retry
      _retainedRef = ref;
      final payload = _buildPayload(user.uid);

      // After an uncertain earlier attempt, first ask the server whether it was stored.
      var alreadyStored = false;
      if (isRetry) {
        try {
          alreadyStored = await CampusBackend.existsOnServer(ref);
        } on FirebaseException {
          alreadyStored = false; // cannot tell: fall through to the write below
        }
      }
      if (!alreadyStored) {
        await ref.set(payload); // completes only when the backend acknowledges the write
      }
      if (!mounted) return;

      setState(() {
        _lastRequestId = ref.id; // success is recorded ONLY after the acknowledgement
        _retainedRef = null;
      });

      // Verification is separate from submission: if reading fails, the data may still be stored.
      Map<String, dynamic>? stored;
      var verifyFailed = false;
      try {
        stored = await CampusBackend.loadRequest(ref.id);
        if (stored == null) verifyFailed = true;
      } catch (_) {
        verifyFailed = true;
      }
      if (!mounted) return;
      _loadMine(); // refresh the saved-requests list in the background
      _showSuccess(ref.id, stored ?? payload, verifyFailed);
    } on FirebaseException catch (e) {
      // Denied by rules: nothing was stored, so the retained reference is discarded.
      if (e.code == 'permission-denied') _retainedRef = null;
      if (mounted) {
        final msg = backendMessage(e);
        setState(() => _submitError = msg);
        widget.c.snack(msg);
      }
    } catch (e) {
      if (mounted) {
        final msg = backendMessage(e);
        setState(() => _submitError = msg);
        widget.c.snack(msg);
      }
    } finally {
      _pendingTimer?.cancel();
      if (mounted) {
        setState(() {
          _isSubmitting = false;
          _pendingSync = false;
        });
      }
    }
  }

  // RESET: reset the Form AND every piece of state that is not owned by the Form.
  // The document already stored in Firestore is NOT touched.
  void _resetAll({bool silent = false}) {
    if (_isSubmitting) return; // Reset is disabled while saving
    _formKey.currentState?.reset(); // resets all FormFields (dropdown, chips, date, checkbox, text)
    for (final t in _all) {
      t.clear();
    }
    setState(() {
      _category = _urgency = _contact = _attachment = null;
      _date = null;
      _agree = false;
      _lastRequestId = null;
      _retainedRef = null;
      _submitError = null;
      _pendingSync = false;
      _draft
        ..name = ''
        ..studentId = ''
        ..email = ''
        ..phone = ''
        ..subject = ''
        ..description = ''
        ..extra = ''
        ..category = null
        ..urgency = null
        ..contact = null
        ..attachment = null
        ..date = null;
    });
    if (!silent) widget.c.snack('Form cleared. You can start a new request.');
  }

  // Loads the signed-in student's saved requests from the server.
  Future<void> _loadMine() async {
    if (!mounted) return;
    setState(() {
      _mineLoading = true;
      _mineError = null;
    });
    try {
      final list = await CampusBackend.myRequests();
      if (!mounted) return;
      setState(() => _mine = list);
    } catch (e) {
      if (mounted) setState(() => _mineError = backendMessage(e));
    } finally {
      if (mounted) setState(() => _mineLoading = false);
    }
  }

  // Opens the retrieval screen for a pasted request reference.
  void _lookup() {
    final id = _lookupCtl.text.trim();
    if (!RegExp(r'^[A-Za-z0-9]{10,40}$').hasMatch(id)) {
      setState(() => _lookupError = 'Paste the full request reference (letters and digits only).');
      return;
    }
    setState(() => _lookupError = null);
    FocusScope.of(context).unfocus();
    openRequestSummary(context, id);
  }

  // Success feedback: dialog with the Firestore document ID and a summary of the request.
  // [v] is the document read back from the server (or, if that read failed, what was just written).
  void _showSuccess(String id, Map<String, dynamic> v, bool verifyFailed) {

// ───────────── Firebase backend (Authentication + Cloud Firestore) ─────────────
/// One place for every Firebase call, so the form code stays easy to read.
class CampusBackend {
  static const String collection = 'campusRequests';

  static CollectionReference<Map<String, dynamic>> get _col => FirebaseFirestore.instance.collection(collection);

  /// Returns the signed-in user, signing in anonymously the first time.
  static Future<User> ensureUser() async {
    final auth = FirebaseAuth.instance;
    final existing = auth.currentUser;
    if (existing != null) return existing;
    final user = (await auth.signInAnonymously()).user;
    if (user == null) throw StateError('Sign-in was not completed.');
    return user;
  }

  /// Allocates a new auto-generated document reference (the ID is known BEFORE the write).
  static DocumentReference<Map<String, dynamic>> newRef() => _col.doc();

  /// Asks the SERVER whether this document exists (used to confirm an uncertain earlier write).
  static Future<bool> existsOnServer(DocumentReference<Map<String, dynamic>> ref) async {
    final snap = await ref.get(const GetOptions(source: Source.server));
    return snap.exists;
  }

  /// Fetches one request from the SERVER. Returns null when the document does not exist.
  static Future<Map<String, dynamic>?> loadRequest(String requestId) async {
    await ensureUser(); // rules require a signed-in user, even for reads
    final snapshot = await _col.doc(requestId).get(const GetOptions(source: Source.server));
    return snapshot.data();
  }

  /// "My Requests": only documents owned by the current UID (rules do not filter queries for us).
  static Future<List<StoredRequest>> myRequests() async {
    final user = await ensureUser();
    final snap = await _col.where('ownerUid', isEqualTo: user.uid).get(const GetOptions(source: Source.server));
    final list = [for (final d in snap.docs) StoredRequest.fromMap(d.id, d.data())];
    list.sort((a, b) => (b.createdAt?.millisecondsSinceEpoch ?? 0).compareTo(a.createdAt?.millisecondsSinceEpoch ?? 0)); // newest first, no index needed
    return list;
  }
}

/// Turns Firebase exceptions into readable, student-friendly messages.
String backendMessage(Object e) {
  // FirebaseAuthException is a FirebaseException, so it must be checked first.
  if (e is FirebaseAuthException) {
    switch (e.code) {
      case 'operation-not-allowed':
        return 'Anonymous sign-in is switched off. In Firebase Console open Authentication > Sign-in method and enable Anonymous.';
      case 'network-request-failed':
        return 'No internet connection. Your inputs are kept. Check your network and try again.';
      default:
        return 'Sign-in failed (${e.code}). Your inputs are kept. Please try again.';
    }
  }
  if (e is FirebaseException) {
    switch (e.code) {
      case 'permission-denied':
        return 'Access denied. Check sign-in and database rules.';
      case 'unavailable':
        return 'The server cannot be reached right now. Your inputs are kept. Check your connection and try again.';
      default:
        return 'Submission failed (${e.code}). Keep your inputs and try again.';
    }
  }
  return 'Unable to complete the request. Your inputs are kept. Please try again.';
}


// Keys let any code (not only widgets) reach the Navigator and the SnackBar messenger.
final GlobalKey<NavigatorState> navKey = GlobalKey<NavigatorState>();
final GlobalKey<ScaffoldMessengerState> messengerKey = GlobalKey<ScaffoldMessengerState>();

/// Shows a floating SnackBar above whichever route is currently visible.
void snack(String msg, {SnackBarAction? action}) {
  final m = messengerKey.currentState;
  if (m == null) return;
  m
    ..hideCurrentSnackBar()
    ..showSnackBar(SnackBar(behavior: SnackBarBehavior.floating, content: Text(msg), action: action));
}

/// App-wide state shared by the tab shell AND every pushed route.
class AppState extends ChangeNotifier {
  int tab = 0, selected = -1;
  final Set<int> going = {}; // registered event indexes
  final Set<int> requested = {}; // services with a returned 'requested' result

  void setTab(int i) {
    if (tab == i) return;
    tab = i;
    notifyListeners();
  }

  void select(int i) {
    selected = i;
    notifyListeners();
  }

  void setGoing(int i, bool value) {
    value ? going.add(i) : going.remove(i);
    notifyListeners();
  }

  void markRequested(int i) {
    requested.add(i);
    notifyListeners();
  }
}

final AppState appState = AppState();

// Rapid-tap guard (test T10): ignores a second navigation started within 450 ms,
// so double taps never push two copies of the same route.
bool _navLock = false;
bool _acquireNav() {
  if (_navLock) return false;
  _navLock = true;
  Future.delayed(const Duration(milliseconds: 450), () => _navLock = false);
  return true;
}

/// Switches the bottom tab and POPS back to the Dashboard route.
/// We never push a new Dashboard to "go back": popUntil(isFirst) reveals the existing one.
void goTab(int i) {
  appState.setTab(i);
  navKey.currentState?.popUntil((r) => r.isFirst);
}

/// Named-route navigation: Navigator.pushNamed() with a registered AppRoutes constant.
void openRoute(BuildContext context, String name) {
  if (!_acquireNav()) return;
  Navigator.pushNamed(context, name);
}

/// Passes the selected Svc object to Service Details and waits for the returned result.
Future<void> openService(BuildContext context, int i) async {
  if (!_acquireNav()) return;
  appState.select(i); // the selection survives the trip, so the card stays highlighted on return
  final result = await Navigator.pushNamed(context, AppRoutes.serviceDetail, arguments: services[i]);
  // After an await, only use the context if the page that started the navigation still exists.
  if (!context.mounted) return;
  if (result == 'requested') {
    appState.markRequested(i);
    snack(services[i].done); // visible confirmation on the previous route
  }
}

/// DIRECT route: Navigator.push() with a MaterialPageRoute (no route name registered).
/// Event Details returns 'registered' or 'cancelled', which we apply here.
Future<void> openEvent(BuildContext context, int i) async {
  if (!_acquireNav()) return;
  final result = await Navigator.push<String>(
    context,
    MaterialPageRoute<String>(
      settings: const RouteSettings(name: AppRoutes.eventDetail),
      builder: (_) => EventDetailScreen(event: events[i], index: i),
    ),
  );
  if (!context.mounted) return;
  if (result == 'registered' && !appState.going.contains(i)) {
    appState.setGoing(i, true);
    snack('Registered for ${events[i].title}');
  } else if (result == 'cancelled' && appState.going.contains(i)) {
    appState.setGoing(i, false);
    snack('Registration cancelled');
  }
}

/// DIRECT route: opens the stored service request (loaded from the Firestore SERVER by its ID).
void openRequestSummary(BuildContext context, String requestId) {
  if (!_acquireNav()) return;
  Navigator.push<void>(
    context,
    MaterialPageRoute<void>(
      settings: const RouteSettings(name: AppRoutes.requestSummary),
      builder: (_) => RequestSummaryScreen(requestId: requestId),
    ),
  );
}

/// Register / cancel from an event card (no navigation involved).
void toggleGoing(int i) {
  final now = !appState.going.contains(i);
  appState.setGoing(i, now);
  snack(now ? 'Registered for ${events[i].title}' : 'Registration cancelled');
}

/// Fallback for any route name that is not registered. It shows the name that failed.
Route<dynamic> _unknownRoute(RouteSettings settings) => MaterialPageRoute<void>(
  settings: settings,
  builder: (_) => UnknownRouteScreen(routeName: settings.name ?? '(no name)'),
);

/// Builds routes that need arguments. Returning null lets onUnknownRoute handle the name.
Route<dynamic>? _generateRoute(RouteSettings settings) {
  if (settings.name == AppRoutes.serviceDetail) {
    final args = settings.arguments;
    // Validate the argument type instead of crashing on a bad cast.
    if (args is! Svc) return _unknownRoute(settings);
    // EXTENSION 1: custom PageRouteBuilder with a fade + slide-up transition.
    return PageRouteBuilder<Object?>(
      settings: settings,
      transitionDuration: const Duration(milliseconds: 380),
      reverseTransitionDuration: const Duration(milliseconds: 300),
      pageBuilder: (_, __, ___) => ServiceDetailScreen(service: args),
      transitionsBuilder: (_, animation, __, child) {
        final curved = CurvedAnimation(parent: animation, curve: Curves.easeOutCubic, reverseCurve: Curves.easeInCubic);
        return FadeTransition(
          opacity: curved,
          child: SlideTransition(position: Tween<Offset>(begin: const Offset(0, .08), end: Offset.zero).animate(curved), child: child),
        );
      },
    );
  }
  return null;
}


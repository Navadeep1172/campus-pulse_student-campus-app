int _mins(String hhmm) => int.parse(hhmm.substring(0, 2)) * 60 + int.parse(hhmm.substring(3));

/// The next class from now (wraps to Monday's first class at weekends / after the last class).
Slot nextClass([DateTime? now]) {
  final t = now ?? DateTime.now();
  if (t.weekday <= 5) {
    final today = t.weekday - 1;
    final mins = t.hour * 60 + t.minute;
    for (final s in classes) {
      if (s.day > today || (s.day == today && _mins(s.start) > mins)) return s;
    }
  }
  return classes.first;
}

// ═════════════════════════ SHARED WIDGETS ═════════════════════════
class _ArtPainter extends CustomPainter {
  final int seed;
  _ArtPainter(this.seed);
  @override
  void paint(Canvas canvas, Size size) {
    final rect = Offset.zero & size;
    canvas.drawRect(
        rect,
        Paint()
          ..shader = const LinearGradient(colors: [kNavy, kPri, Color(0xFF5B7CFA)], begin: Alignment.topLeft, end: Alignment.bottomRight)
              .createShader(rect));
    final r = math.Random(seed);
    for (int i = 0; i < 4; i++) {
      canvas.drawCircle(Offset(r.nextDouble() * size.width, r.nextDouble() * size.height), size.shortestSide * (.25 + r.nextDouble() * .5),
          Paint()..color = Colors.white.withOpacity(.05 + r.nextDouble() * .06));
    }
  }

  @override
  bool shouldRepaint(covariant _ArtPainter o) => false;
}

/// IUT logo (International University of Technology), drawn in code so it stays sharp at
/// any size and follows light / dark mode: red dot + "iUT" mark, thin divider and the
/// three-line university name. [height] is the height of the whole logo.
/// [onDark] forces white ink (use it on navy / photo backgrounds).
class IutLogo extends StatelessWidget {
  final double height;
  final bool onDark;
  const IutLogo(this.height, {super.key, this.onDark = false});

  @override
  Widget build(BuildContext context) {
    final p = Pal.of(context);
    final ink = onDark ? Colors.white : (p.dark ? const Color(0xFFE6ECFF) : kIutBlue);
    final s = height / 220; // the artwork is designed on a 220-unit grid
    final line = TextStyle(color: ink, fontWeight: FontWeight.w800, fontSize: 64 * s, height: 1.08, letterSpacing: 0);
    return Semantics(
      label: 'International University of Technology',
      child: ExcludeSemantics(
        child: Row(mainAxisSize: MainAxisSize.min, crossAxisAlignment: CrossAxisAlignment.center, children: [
          CustomPaint(size: Size(387 * s, height), painter: _IutMarkPainter(ink)),
          SizedBox(width: 34 * s),
          Container(width: math.max(1.5, 5 * s), height: height * .95, color: ink),
          SizedBox(width: 38 * s),
          Column(mainAxisSize: MainAxisSize.min, crossAxisAlignment: CrossAxisAlignment.start, children: [
            Text('INTERNATIONAL', style: line),
            Text('UNIVERSITY OF', style: line),
            Text('TECHNOLOGY', style: line),
          ]),
        ]),
      ),
    );
  }
}

/// Paints the "iUT" mark on a 387 x 220 grid, scaled to the given size.
class _IutMarkPainter extends CustomPainter {
  final Color ink;
  const _IutMarkPainter(this.ink);

  @override
  void paint(Canvas canvas, Size size) {
    canvas.scale(size.width / 387, size.height / 220);
    final fill = Paint()..color = ink..style = PaintingStyle.fill;

    // Red dot of the "i"
    canvas.drawCircle(const Offset(30, 29), 29, Paint()..color = kIutRed);
    // Stem of the "i"
    canvas.drawRRect(RRect.fromRectAndCorners(const Rect.fromLTWH(0, 68, 60, 152), bottomLeft: const Radius.circular(10), bottomRight: const Radius.circular(10)), fill);

    // "U": two stems joined by a rounded bottom
    const c = Offset(154.5, 142.5);
    final u = Path()
      ..moveTo(77, 30)
      ..lineTo(77, c.dy)
      ..arcTo(Rect.fromCircle(center: c, radius: 77.5), math.pi, -math.pi, false)
      ..lineTo(232, 30)
      ..lineTo(174, 30)
      ..lineTo(174, c.dy)
      ..arcTo(Rect.fromCircle(center: c, radius: 19.5), 0, math.pi, false)
      ..lineTo(135, 30)
      ..close();
    canvas.drawPath(u, fill);

    // "T": top bar + stem
    canvas.drawRect(const Rect.fromLTWH(222, 30, 165, 45), fill);
    canvas.drawRect(const Rect.fromLTWH(273, 30, 63, 190), fill);
  }

  @override
  bool shouldRepaint(covariant _IutMarkPainter o) => o.ink != ink;
}

/// Photo: tries assets/images/<asset> first, then the internet, then generated artwork.
class Photo extends StatelessWidget {
  final String id, asset;
  final int seed;
  const Photo(this.id, {super.key, this.asset = '', this.seed = 1});
  @override
  Widget build(BuildContext context) {
    Widget art() => CustomPaint(painter: _ArtPainter(seed), size: Size.infinite);
    final net = Image.network(
      'https://images.unsplash.com/photo-$id?auto=format&fit=crop&w=1400&q=70',
      fit: BoxFit.cover,
      width: double.infinity,
      height: double.infinity,
      errorBuilder: (_, __, ___) => art(),
      loadingBuilder: (_, child, prog) => prog == null ? child : art(),
    );
    if (asset.isEmpty) return net;
    return Image.asset('assets/images/$asset',
        fit: BoxFit.cover, width: double.infinity, height: double.infinity, errorBuilder: (_, __, ___) => net);
  }
}

